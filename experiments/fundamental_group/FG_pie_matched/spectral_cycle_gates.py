"""
spectral_cycle_gates.py -- C6 (spectral) and C7 (cycle) GATES, not probes
=========================================================================
Deterministic computation on the EXACT pairs used in the reported runs.
No training, no learned probe.

WHY GATES BEAT PROBES
---------------------
If two complexes have identical eigenvalue multisets, then any function of the
spectrum alone provably cannot separate them -- a spectral probe (SPEC_MLP)
must fail, so running one adds no information. The gate subsumes the probe.
Only if a gate FAILS do you need a probe, to characterise how exploitable the
leak is.

C6 -- SPECTRAL.  Eigenvalue multisets compared at tol 1e-8:
    1-skeleton         : adjacency, combinatorial Laplacian, normalised Laplacian
    Hasse graph        : adjacency, Laplacian, and a rank-coloured variant
                         (A + diag(w_rank)) so the rank colouring is not
                         discarded by the spectrum
    Hodge Laplacians   : L0 = B1 B1^T,  L1 = B1^T B1 + B2 B2^T,  L2 = B2^T B2
                         computed TWICE -- once from UNSIGNED incidence (what
                         the unsigned incidence pipeline actually supplies) and
                         once from SIGNED incidence -- and reported separately.

C7 -- CYCLE.  Girth, plus exact simple-cycle counts by length for every
    l <= L, with L stated explicitly.

    HONEST BOUND ON L.  Exact simple-cycle enumeration grows ~4x per unit
    length on these complexes. Measured on the largest pair member
    (|V|=130, |E|=492): l<=8 takes 25 s, l<=9 takes 119 s, and l<=12 would
    take hours PER COMPLEX (x32 complexes). L=12 or L=16 is therefore NOT
    achievable by enumeration and is not claimed here. Default L=8; --cycle-L
    can raise it if you are willing to pay.

    The unbounded statement comes from C6 instead, and is strictly stronger
    on the walk side: closed-walk counts satisfy tr(A^l) = sum_i lambda_i^l,
    so if the adjacency spectra match, closed-walk counts match at EVERY
    length l, with no bound at all. Message passing aggregates walks, not
    simple cycles, so this is the quantity that actually bounds the ladder's
    receptive field. This script verifies tr(A^l) directly as a cross-check.

PAIR PROVENANCE
---------------
The 16 pairs are regenerated by replaying the cache RNG stream
(data_rng = default_rng(data_seed); derived_seed = data_rng.integers(...) per
pair), then VALIDATED field-by-field against a run's certificates.jsonl.
The script refuses to report if the regenerated pairs do not match.

Usage:
    python spectral_cycle_gates.py --certificates <run>/certificates.jsonl
    python spectral_cycle_gates.py --cycle-L 9 --pairs 16
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
import warnings
from collections import Counter
from pathlib import Path

warnings.filterwarnings("ignore")

import networkx as nx
import numpy as np


def _fg_dir() -> Path:
    env = os.environ.get("FG_GENUS2_DIR")
    here = Path(__file__).resolve()
    candidates = []
    if env:
        candidates.append(Path(env))
    candidates += [
        here.parent.parent / "FG_genus_2",
        here.parent.parent.parent / "fundamental_group" / "FG_genus_2",
    ]
    for c in candidates:
        if (c / "fundamental_group_dataset_genus2.py").is_file():
            return c
    raise RuntimeError("Set FG_GENUS2_DIR to the FG_genus_2 directory.")


FG_DIR = _fg_dir()
for _path in (FG_DIR, FG_DIR.parent):
    if str(_path) not in sys.path:
        sys.path.insert(0, str(_path))

from fundamental_group_dataset_genus2 import generate_tight_pair_descriptor  # noqa: E402

TOL = 1e-8


# --------------------------------------------------------------------------
# matrices
# --------------------------------------------------------------------------
def incidence_matrices(edges, faces, signed: bool):
    """B1 (V x E) and B2 (E x F). Signed uses the simplicial orientation
    convention already used by fg_core.betti_numbers; unsigned is |.|."""
    verts = sorted({v for e in edges for v in e})
    vidx = {v: i for i, v in enumerate(verts)}
    eidx = {tuple(sorted(e)): i for i, e in enumerate(edges)}
    B1 = np.zeros((len(verts), len(edges)))
    for e, j in eidx.items():
        u, v = e
        B1[vidx[u], j] = -1.0 if signed else 1.0
        B1[vidx[v], j] = 1.0
    B2 = np.zeros((len(edges), len(faces)))
    for j, face in enumerate(faces):
        a, b, c = sorted(face)
        if signed:
            B2[eidx[(b, c)], j] += 1.0
            B2[eidx[(a, c)], j] += -1.0
            B2[eidx[(a, b)], j] += 1.0
        else:
            B2[eidx[(b, c)], j] += 1.0
            B2[eidx[(a, c)], j] += 1.0
            B2[eidx[(a, b)], j] += 1.0
    return B1, B2


def hasse_graph(edges, faces) -> nx.Graph:
    G = nx.Graph()
    eidx = {tuple(sorted(e)): i for i, e in enumerate(edges)}
    for v in sorted({v for e in edges for v in e}):
        G.add_node(("v", v), rank=0)
    for e, i in eidx.items():
        G.add_node(("e", i), rank=1)
        for v in e:
            G.add_edge(("e", i), ("v", v))
    for j, face in enumerate(faces):
        G.add_node(("f", j), rank=2)
        a, b, c = sorted(face)
        for e in ((a, b), (a, c), (b, c)):
            if e in eidx:
                G.add_edge(("f", j), ("e", eidx[e]))
    return G


def spec(M) -> np.ndarray:
    return np.sort(np.linalg.eigvalsh((M + M.T) / 2.0))


def all_spectra(edges, faces) -> dict:
    out = {}
    G = nx.Graph()
    G.add_edges_from(edges)
    nodes = sorted(G.nodes())
    A = nx.to_numpy_array(G, nodelist=nodes)
    d = A.sum(1)
    out["skeleton_adjacency"] = spec(A)
    out["skeleton_laplacian"] = spec(np.diag(d) - A)
    dinv = np.divide(1.0, np.sqrt(d), out=np.zeros_like(d), where=d > 0)
    out["skeleton_norm_laplacian"] = spec(np.eye(len(nodes)) - (dinv[:, None] * A * dinv[None, :]))

    H = hasse_graph(edges, faces)
    hnodes = sorted(H.nodes(), key=repr)
    AH = nx.to_numpy_array(H, nodelist=hnodes)
    dH = AH.sum(1)
    out["hasse_adjacency"] = spec(AH)
    out["hasse_laplacian"] = spec(np.diag(dH) - AH)
    # rank-coloured: the plain spectrum discards node colours, so add a
    # rank-dependent diagonal to make the colouring spectrally visible
    rank_w = np.array([{"v": 1.0, "e": 2.0, "f": 3.0}[n[0]] for n in hnodes])
    out["hasse_rank_coloured_adjacency"] = spec(AH + np.diag(rank_w))

    for signed in (True, False):
        tag = "signed" if signed else "unsigned"
        B1, B2 = incidence_matrices(edges, faces, signed=signed)
        out[f"hodge_L0_{tag}"] = spec(B1 @ B1.T)
        out[f"hodge_L1_{tag}"] = spec(B1.T @ B1 + B2 @ B2.T)
        out[f"hodge_L2_{tag}"] = spec(B2.T @ B2)
    return out


def closed_walks(edges, max_len: int) -> list:
    """tr(A^l) for l = 1..max_len. Spectrally determined: equal adjacency
    spectra => these agree at EVERY length."""
    G = nx.Graph()
    G.add_edges_from(edges)
    A = nx.to_numpy_array(G, nodelist=sorted(G.nodes()))
    out, M = [], np.eye(A.shape[0])
    for _ in range(max_len):
        M = M @ A
        out.append(float(np.trace(M)))
    return out


def cycle_profile(edges, L: int):
    G = nx.Graph()
    G.add_edges_from(edges)
    counts = Counter(len(c) for c in nx.simple_cycles(G, length_bound=L))
    return int(nx.girth(G)), {l: int(counts.get(l, 0)) for l in range(3, L + 1)}


# --------------------------------------------------------------------------
# pair regeneration + provenance validation
# --------------------------------------------------------------------------
def regenerate_pairs(n_pairs, data_seed, noise_pairs_per_g, subdivision,
                     max_tries, max_expansions):
    data_rng = np.random.default_rng(data_seed)
    noise_candidates = tuple(sorted({
        max(1, noise_pairs_per_g), max(1, noise_pairs_per_g * 2),
        max(1, noise_pairs_per_g * 4)}))
    pairs = []
    for _ in range(n_pairs):
        derived = int(data_rng.integers(0, np.iinfo(np.uint32).max, dtype=np.uint32))
        pair, _meta, cert = generate_tight_pair_descriptor(
            seed=derived, noise_candidates=noise_candidates,
            subdivision=subdivision,
            max_attempts=max(5_000, max_tries * max_expansions * 5))
        pairs.append((pair, cert))
    return pairs


def validate_provenance(pairs, cert_path: Path) -> bool:
    if not cert_path or not cert_path.is_file():
        print(f"  !! no certificates.jsonl given -- provenance UNVERIFIED")
        return False
    ref = {}
    for line in cert_path.read_text().splitlines():
        if line.strip():
            r = json.loads(line)
            ref[int(r["pair_index"])] = r
    keys = ["attempts", "word_path_length", "configured_noise_pairs_per_g",
            "hasse_wl_rounds_to_stability", "euler_characteristic"]
    ok = True
    for i, (_pair, cert) in enumerate(pairs):
        if i not in ref:
            print(f"  pair {i}: absent from certificates.jsonl"); ok = False; continue
        for k in keys:
            if cert.get(k) != ref[i].get(k):
                print(f"  pair {i}: {k} regenerated={cert.get(k)} run={ref[i].get(k)}")
                ok = False
        if list(cert["rank_counts"]) != list(ref[i]["rank_counts"]):
            print(f"  pair {i}: rank_counts mismatch"); ok = False
    print(f"  provenance: regenerated pairs {'MATCH' if ok else 'DO NOT MATCH'} the run's certificates")
    return ok


# --------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pairs", type=int, default=16)
    ap.add_argument("--data-seed", type=int, default=0)
    ap.add_argument("--noise-pairs-per-g", type=int, default=2)
    ap.add_argument("--subdivision", type=int, default=3)
    ap.add_argument("--max-tries", type=int, default=100)
    ap.add_argument("--max-expansions", type=int, default=10)
    ap.add_argument("--cycle-L", type=int, default=8,
                    help="max simple-cycle length (see docstring: >9 is expensive)")
    ap.add_argument("--walk-L", type=int, default=16,
                    help="max closed-walk length for tr(A^l) cross-check")
    ap.add_argument("--certificates", type=str, default="",
                    help="path to a run's certificates.jsonl for provenance check")
    ap.add_argument("--out", type=str, default="c6_c7_results.json")
    args = ap.parse_args()

    print("=" * 78)
    print("C6 (spectral) + C7 (cycle) GATES on the reported genus-2 pairs")
    print("=" * 78)
    print(f"regenerating {args.pairs} pairs from data_seed={args.data_seed} ...")
    t0 = time.time()
    pairs = regenerate_pairs(args.pairs, args.data_seed, args.noise_pairs_per_g,
                             args.subdivision, args.max_tries, args.max_expansions)
    print(f"  done in {time.time()-t0:.1f}s")
    provenance_ok = validate_provenance(
        pairs, Path(args.certificates) if args.certificates else None)

    spectral_keys = None
    spec_tally, walk_tally, cycle_tally = Counter(), 0, 0
    girth_tally = 0
    per_pair = []

    for i, (pair, cert) in enumerate(pairs):
        ea, fa = pair.surface_edges, pair.surface_faces
        eb, fb = pair.free_edges, pair.free_faces

        sa, sb = all_spectra(ea, fa), all_spectra(eb, fb)
        spectral_keys = list(sa.keys())
        spec_match = {}
        for k in spectral_keys:
            same = (sa[k].shape == sb[k].shape and
                    np.allclose(sa[k], sb[k], atol=TOL, rtol=0.0))
            spec_match[k] = bool(same)
            spec_tally[k] += int(same)

        wa = closed_walks(ea, args.walk_L)
        wb = closed_walks(eb, args.walk_L)
        walks_same = np.allclose(wa, wb, atol=1e-6, rtol=1e-9)
        walk_tally += int(walks_same)

        t = time.time()
        ga, ca = cycle_profile(ea, args.cycle_L)
        gb, cb = cycle_profile(eb, args.cycle_L)
        cyc_same = (ca == cb)
        girth_same = (ga == gb)
        cycle_tally += int(cyc_same)
        girth_tally += int(girth_same)

        per_pair.append({
            "pair_index": i, "rank_counts": list(cert["rank_counts"]),
            "spectral": spec_match, "closed_walks_match": bool(walks_same),
            "girth": [ga, gb], "girth_match": bool(girth_same),
            "cycle_counts_match": bool(cyc_same),
            "cycles_a": ca, "cycles_b": cb,
        })
        n_spec_ok = sum(spec_match.values())
        print(f"  pair {i:>2} |V,E,F|={tuple(cert['rank_counts'])}  "
              f"spectra {n_spec_ok}/{len(spectral_keys)}  walks={walks_same}  "
              f"girth={ga}/{gb}  cycles(l<={args.cycle_L})={cyc_same}  "
              f"[{time.time()-t:.1f}s]")

    n = len(pairs)
    print("\n" + "=" * 78)
    print(f"C6 SPECTRAL GATE  (tol={TOL:g}, {n} pairs)")
    print("=" * 78)
    for k in spectral_keys:
        verdict = "GATE-MATCHED" if spec_tally[k] == n else "LEAK"
        print(f"  {k:34s} {spec_tally[k]:>3}/{n}   {verdict}")
    print(f"\n  closed walks tr(A^l), l<={args.walk_L}: {walk_tally}/{n}")
    print("    (spectrally implied: equal adjacency spectra => equal at EVERY l)")

    print("\n" + "=" * 78)
    print(f"C7 CYCLE GATE  (exact enumeration, L={args.cycle_L})")
    print("=" * 78)
    print(f"  girth equal                        {girth_tally:>3}/{n}")
    print(f"  cycle counts equal for 3<=l<={args.cycle_L:<8} {cycle_tally:>3}/{n}   "
          f"{'GATE-MATCHED up to L' if cycle_tally == n else 'LEAK'}")
    print(f"\n  Report as: \"matched for l <= {args.cycle_L}\" -- a number, not "
          f"the adjective 'partial'.")

    summary = {
        "n_pairs": n, "tolerance": TOL, "cycle_L": args.cycle_L,
        "walk_L": args.walk_L, "provenance_validated": provenance_ok,
        "spectral_matched": {k: spec_tally[k] for k in spectral_keys},
        "closed_walks_matched": walk_tally,
        "girth_matched": girth_tally, "cycle_counts_matched": cycle_tally,
        "per_pair": per_pair,
    }
    Path(args.out).write_text(json.dumps(summary, indent=2, sort_keys=True))
    print(f"\nwrote {args.out}")
    if not provenance_ok:
        print("WARNING: provenance unverified -- do not report these numbers "
              "as being about the evaluated pairs until it passes.")


if __name__ == "__main__":
    main()
